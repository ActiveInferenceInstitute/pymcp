#!/usr/bin/env python3
"""Generate the gate's measured facts.

The numbers in `docs/_generated/gate-facts.md` are produced here, never typed
by hand: per-arm wall times, the collected test counts, and the slow-marked
split. `.github/workflows/ci.yml` does not run this; `./run.sh docs` does, in
check mode.

    ./run.sh setup && uv run --frozen python scripts/gate_facts.py --record
    uv run --frozen python scripts/gate_facts.py --check

`--record` re-runs every gate arm through `./run.sh` (so the timing describes
the real entry point), writes `docs/_generated/arms.json`, and renders the
Markdown. `--check` re-renders from `docs/_generated/arms.json` and fails if the
committed Markdown differs, which catches a hand-edited table. Neither mode
claims a speedup: the receipt records whatever the host measured.
"""

from __future__ import annotations

import json
import platform
import subprocess
import sys
import time
from datetime import UTC, datetime
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = REPO_ROOT / "docs" / "_generated"
RECEIPT = OUT_DIR / "arms.json"
FACTS = OUT_DIR / "gate-facts.md"
SCHEMA = "pymcp-gate-facts/v1"
ARMS = ("lint", "test", "test-full", "links", "gnn")
TIMED_SETS = {"test": "fast arm", "test-full": "full suite"}
# `uv --version` prints "uv X.Y.Z (…)", so the renderer embeds it verbatim.


def run(command: list[str]) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        command,
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=False,
    )


def pytest(argv: list[str]) -> subprocess.CompletedProcess[str]:
    return run(["uv", "run", "--frozen", "python", "-m", "pytest", *argv])


def tool_version(command: list[str]) -> str:
    completed = run(command)
    return (completed.stdout or completed.stderr).strip().splitlines()[0]


def test_counts() -> dict:
    collected = pytest(["tests/", "--collect-only", "-q"])
    slow = pytest(["tests/", "--collect-only", "-q", "-m", "slow"])
    if collected.returncode != 0:
        raise SystemExit(f"pytest collection failed:\n{collected.stderr}")

    per_file: dict[str, int] = {}
    for line in collected.stdout.splitlines():
        if "::" in line:
            per_file[line.split("::", 1)[0]] = per_file.get(
                line.split("::", 1)[0], 0
            ) + 1
    slow_per_file: dict[str, int] = {}
    for line in slow.stdout.splitlines():
        if "::" in line:
            name = line.split("::", 1)[0]
            slow_per_file[name] = slow_per_file.get(name, 0) + 1

    summary = collected.stdout.strip().splitlines()[-1]
    return {
        "collected": int(summary.split()[0]),
        "slow": sum(slow_per_file.values()),
        "files": {
            path: {"collected": count, "slow": slow_per_file.get(path, 0)}
            for path, count in sorted(per_file.items())
        },
    }


def record() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    if not FACTS.exists():
        # The `links` arm below requires generated pages to exist. Bootstrap the
        # page so the first recorded run on a fresh checkout measures the link
        # check instead of its absence; the render at the end replaces this.
        FACTS.write_text(
            "# Gate facts\n\n<!-- pending: regenerated by scripts/gate_facts.py -->\n"
        )

    arms = []
    for arm in ARMS:
        started = time.monotonic()
        completed = run(["./run.sh", arm])
        seconds = round(time.monotonic() - started, 2)
        status = "pass" if completed.returncode == 0 else "fail"
        print(f"{arm:10s} {seconds:7.2f}s  {status}", file=sys.stderr)
        arms.append(
            {
                "arm": arm,
                "command": f"./run.sh {arm}",
                "seconds": seconds,
                "status": status,
            }
        )

    receipt = {
        "schema": SCHEMA,
        "recorded": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "commit": run(["git", "rev-parse", "--short", "HEAD"]).stdout.strip(),
        "host": f"{platform.system()} {platform.machine()}",
        "python": platform.python_version(),
        "uv": tool_version(["uv", "--version"]),
        "arms": arms,
        "tests": test_counts(),
    }
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    RECEIPT.write_text(json.dumps(receipt, indent=2, sort_keys=True) + "\n")
    FACTS.write_text(render(receipt))

    failed = [arm["arm"] for arm in arms if arm["status"] != "pass"]
    if failed:
        print(f"recorded, but these arms failed: {', '.join(failed)}", file=sys.stderr)
        return 1
    return 0


def render(receipt: dict) -> str:
    tests = receipt["tests"]
    lines = [
        "# Gate facts",
        "",
        "<!-- generated by `scripts/gate_facts.py --record`; do not edit -->",
        "",
        f"Recorded `{receipt['recorded']}` at commit `{receipt['commit']}` on "
        f"{receipt['host']} with {receipt['uv']} and Python "
        f"{receipt['python']}. Wall times are one run per arm of the real "
        "entry point on one host; they describe that host, not a benchmark claim.",
        "",
        "## Arms",
        "",
        "| Arm | Command | Wall time | Result |",
        "| --- | --- | --- | --- |",
    ]
    for arm in receipt["arms"]:
        extra = TIMED_SETS.get(arm["arm"])
        label = f"{arm['arm']} ({extra})" if extra else arm["arm"]
        lines.append(
            f"| {label} | `{arm['command']}` | {arm['seconds']:.2f}s | "
            f"{arm['status']} |"
        )
    lines += [
        "",
        "`./run.sh setup` is excluded: it is the one-time frozen-lock install, "
        "not a gate arm.",
        "",
        "## Test suite",
        "",
        f"`pytest tests/` collects **{tests['collected']}** tests across "
        f"{len(tests['files'])} files; **{tests['slow']}** are marked `slow` "
        "and are the only tests `./run.sh test` deselects.",
        "",
        "| File | Collected | Slow-marked |",
        "| --- | --- | --- |",
    ]
    for path, counts in tests["files"].items():
        lines.append(f"| `{path}` | {counts['collected']} | {counts['slow']} |")
    lines.append("")
    return "\n".join(lines)


def check() -> int:
    if not RECEIPT.exists():
        print(
            "docs/_generated/arms.json is missing; run "
            "`uv run --frozen python scripts/gate_facts.py --record`",
            file=sys.stderr,
        )
        return 1
    expected = render(json.loads(RECEIPT.read_text(encoding="utf-8")))
    actual = FACTS.read_text() if FACTS.exists() else ""
    if expected != actual:
        print(
            "docs/_generated/gate-facts.md is out of date with "
            "docs/_generated/arms.json; re-record with "
            "`uv run --frozen python scripts/gate_facts.py --record`",
            file=sys.stderr,
        )
        return 1
    print("generated gate facts are current")
    return 0


def main(argv: list[str]) -> int:
    if "--record" in argv:
        return record()
    if "--check" in argv:
        return check()
    print(__doc__, file=sys.stderr)
    print("expected --record or --check", file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
